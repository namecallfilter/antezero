-- Emits sim/src/data_gen.rs from the live game prototypes (G.P_CENTERS etc.),
-- so that keys, ordering, costs, rarities and pool membership are exactly the
-- game's. Regenerate from sim/ with:
--   cargo run --release -p oracle --bin ocli -- "(function() dofile(HARNESS_DIR..'/gen_data.lua'); return GEN() end)()" > src/data_gen.rs

local function camel(key)
  local s = key:gsub('^[a-z]+_', '')
  local out = ''
  for part in s:gmatch('[^_]+') do
    out = out .. part:sub(1,1):upper() .. part:sub(2)
  end
  if out:match('^%d') then out = 'J' .. out end
  return out
end

local function opt_str(s) return s and ('Some("'..s..'")') or 'None' end
local function b(v) return v and 'true' or 'false' end
-- Shortest decimal that reads back as the same double.
local function num(v)
  if v == nil then return '0.0' end
  local s
  for digits = 15, 17 do
    s = string.format('%.'..digits..'g', v)
    if tonumber(s) == v then break end
  end
  if not s:find('[%.eEn]') then s = s .. '.0' end
  return s
end

-- 'Five of a Kind' -> HandType::FiveOfAKind
local function hand(h)
  if not h then return 'None' end
  local name = h:gsub('(%a)(%w*)', function(a, r) return a:upper()..r end):gsub(' ', '')
  return 'Some(HandType::'..name..')'
end

function GEN()
  local o = {}
  local function w(s) o[#o+1] = s end
  w('// @generated by oracle/lua/gen_data.lua from the Balatro 1.0.1o prototypes.')
  w('// Do not edit by hand.')
  w('use super::data::*;')
  w('')

  -- Jokers
  local J = G.P_CENTER_POOLS.Joker
  w('#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]')
  w('#[repr(u8)]')
  w('pub enum Joker {')
  for i, v in ipairs(J) do w('    '..camel(v.key)..' = '..(i-1)..',') end
  w('}')
  w('pub const JOKER_COUNT: usize = '..#J..';')
  w('pub const ALL_JOKERS: [Joker; '..#J..'] = [')
  for _, v in ipairs(J) do w('    Joker::'..camel(v.key)..',') end
  w('];')
  w('pub const JOKER_DEFS: [JokerDef; '..#J..'] = [')
  for _, v in ipairs(J) do
    local gate = v.enhancement_gate and ('Some(Enhancement::'..camel(v.enhancement_gate)..')') or 'None'
    w(string.format('    JokerDef { key: "%s", name: "%s", rarity: %d, cost: %d, perishable_compat: %s, eternal_compat: %s, enhancement_gate: %s, no_pool_flag: %s, yes_pool_flag: %s },',
      v.key, v.name, v.rarity, v.cost, b(v.perishable_compat), b(v.eternal_compat), gate,
      opt_str(v.no_pool_flag), opt_str(v.yes_pool_flag)))
  end
  w('];')
  -- rarity pools (game order)
  for r = 1, 4 do
    local P = G.P_JOKER_RARITY_POOLS[r]
    w('pub const RARITY_POOL_'..r..': [Joker; '..#P..'] = [')
    for _, v in ipairs(P) do w('    Joker::'..camel(v.key)..',') end
    w('];')
  end
  w('')

  local function consumable_set(set, ename)
    local P = G.P_CENTER_POOLS[set]
    w('#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]')
    w('#[repr(u8)]')
    w('pub enum '..ename..' {')
    for i, v in ipairs(P) do w('    '..camel(v.key)..' = '..(i-1)..',') end
    w('}')
    w('pub const ALL_'..ename:upper()..'S: ['..ename..'; '..#P..'] = [')
    for _, v in ipairs(P) do w('    '..ename..'::'..camel(v.key)..',') end
    w('];')
    w('pub const '..ename:upper()..'_DEFS: [ConsumableDef; '..#P..'] = [')
    for _, v in ipairs(P) do
      w(string.format('    ConsumableDef { key: "%s", name: "%s", cost: %d, hand_type: %s, max_highlighted: %d, min_highlighted: %d },',
        v.key, v.name, v.cost, hand(v.config.hand_type), v.config.max_highlighted or 0, v.config.min_highlighted or 0))
    end
    w('];')
    w('')
  end
  consumable_set('Tarot', 'Tarot')
  consumable_set('Planet', 'Planet')
  consumable_set('Spectral', 'Spectral')

  -- Vouchers
  local V = G.P_CENTER_POOLS.Voucher
  w('#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]')
  w('#[repr(u8)]')
  w('pub enum Voucher {')
  for i, v in ipairs(V) do w('    '..camel(v.key)..' = '..(i-1)..',') end
  w('}')
  w('pub const ALL_VOUCHERS: [Voucher; '..#V..'] = [')
  for _, v in ipairs(V) do w('    Voucher::'..camel(v.key)..',') end
  w('];')
  w('pub const VOUCHER_DEFS: [VoucherDef; '..#V..'] = [')
  for _, v in ipairs(V) do
    local req = (v.requires and v.requires[1]) and ('Some(Voucher::'..camel(v.requires[1])..')') or 'None'
    w(string.format('    VoucherDef { key: "%s", name: "%s", cost: %d, requires: %s, extra: %s },',
      v.key, v.name, v.cost, req, num(type(v.config.extra) == 'number' and v.config.extra or 0)))
  end
  w('];')
  w('')

  -- Boosters
  local B = G.P_CENTER_POOLS.Booster
  w('#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]')
  w('#[repr(u8)]')
  w('pub enum Booster {')
  for i, v in ipairs(B) do w('    '..camel(v.key)..' = '..(i-1)..',') end
  w('}')
  w('pub const ALL_BOOSTERS: [Booster; '..#B..'] = [')
  for _, v in ipairs(B) do w('    Booster::'..camel(v.key)..',') end
  w('];')
  w('pub const BOOSTER_DEFS: [BoosterDef; '..#B..'] = [')
  for _, v in ipairs(B) do
    w(string.format('    BoosterDef { key: "%s", name: "%s", kind: PackKind::%s, cost: %d, weight: %s, extra: %d, choose: %d },',
      v.key, v.name, v.kind, v.cost, num(v.weight), v.config.extra, v.config.choose))
  end
  w('];')
  w('')

  -- Tags
  local T = G.P_CENTER_POOLS.Tag
  w('#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]')
  w('#[repr(u8)]')
  w('pub enum TagKind {')
  for i, v in ipairs(T) do w('    '..camel(v.key)..' = '..(i-1)..',') end
  w('}')
  w('pub const ALL_TAGS: [TagKind; '..#T..'] = [')
  for _, v in ipairs(T) do w('    TagKind::'..camel(v.key)..',') end
  w('];')
  w('pub const TAG_DEFS: [TagDef; '..#T..'] = [')
  for _, v in ipairs(T) do
    w(string.format('    TagDef { key: "%s", name: "%s", min_ante: %d },',
      v.key, v.name, v.min_ante or 0))
  end
  w('];')
  w('')

  -- Blinds (sorted by key, which is the order pseudorandom_element uses)
  local keys = {}
  for k, v in pairs(G.P_BLINDS) do keys[#keys+1] = k end
  table.sort(keys)
  w('#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]')
  w('#[repr(u8)]')
  w('pub enum BlindKind {')
  for i, k in ipairs(keys) do w('    '..camel(k)..' = '..(i-1)..',') end
  w('}')
  w('pub const ALL_BLINDS: [BlindKind; '..#keys..'] = [')
  for _, k in ipairs(keys) do w('    BlindKind::'..camel(k)..',') end
  w('];')
  w('pub const BLIND_DEFS: [BlindDef; '..#keys..'] = [')
  for _, k in ipairs(keys) do
    local v = G.P_BLINDS[k]
    w(string.format('    BlindDef { key: "%s", name: "%s", dollars: %d, mult: %s, boss: %s, showdown: %s, min_ante: %d },',
      k, v.name, v.dollars, num(v.mult), b(v.boss ~= nil), b(v.boss and v.boss.showdown), v.boss and v.boss.min or 0))
  end
  w('];')
  w('')

  -- Backs
  local K = G.P_CENTER_POOLS.Back
  local backs = {}
  for _, v in ipairs(K) do backs[#backs+1] = v end
  table.sort(backs, function(a, c) return a.order < c.order end)
  w('#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]')
  w('#[repr(u8)]')
  w('pub enum Back {')
  for i, v in ipairs(backs) do w('    '..camel(v.key)..' = '..(i-1)..',') end
  w('    Challenge = '..#backs..',')
  w('}')
  w('pub const BACK_DEFS: [BackDef; '..(#backs+1)..'] = [')
  for _, v in ipairs(backs) do w(string.format('    BackDef { key: "%s", name: "%s" },', v.key, v.name)) end
  w('    BackDef { key: "b_challenge", name: "Challenge Deck" },')
  w('];')
  w('pub const ALL_BACKS: [Back; '..(#backs+1)..'] = [')
  for _, v in ipairs(backs) do w('    Back::'..camel(v.key)..',') end
  w('    Back::Challenge,')
  w('];')

  return table.concat(o, '\n')..'\n'
end
